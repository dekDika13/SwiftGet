_cache = {}


def _svg(name, color, width=1.9):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
            f'stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round">{P[name]}</svg>')


def _render(svg, size):
    pm = QPixmap(size * 2, size * 2)
    pm.fill(Qt.transparent)
    p = QPainter(pm)
    p.setRenderHint(QPainter.Antialiasing)
    QSvgRenderer(QByteArray(svg.encode())).render(p)
    p.end()
    pm.setDevicePixelRatio(2)
    return pm


def pixmap(name, color="#ffffff", size=18):
    k = (name, color, size)
    if k not in _cache:
        _cache[k] = _render(_svg(name, color), size)
    return _cache[k]


def icon(name, color="#ffffff", dim="#888888", size=22):
    ic = QIcon()
    ic.addPixmap(pixmap(name, color, size), QIcon.Normal)
    ic.addPixmap(pixmap(name, dim, size), QIcon.Disabled)
    return ic


